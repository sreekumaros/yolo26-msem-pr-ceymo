#!/usr/bin/env python3
"""Turn results/*.json + split_stats.json into results_macros.tex for the manuscript.

Every experimental number in the revised paper is read through
\\res{<variant>}{<split>}{<metric>} (mean over seeds) and \\resstd{...} (std),
\\gain{<variant>}{<split>}{<metric>} (mean difference to baseline_p256), and
\\stat{<split>}{<field>} for dataset statistics. Missing values render as a red
"??" so nothing unmeasured can slip into the submission.
"""
from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

import numpy as np

METRICS = {  # macro name -> (json path, scale)
    "boxmapfifty": (("box", "mAP50"), 100), "boxmap": (("box", "mAP50_95"), 100),
    "maskp": (("mask", "P"), 100), "maskr": (("mask", "R"), 100),
    "maskmapfifty": (("mask", "mAP50"), 100), "maskmap": (("mask", "mAP50_95"), 100),
    "miou": (("mIoU",), 100), "biouthree": (("BIoU_3px",), 100), "bioudiag": (("BIoU_2pct_diag",), 100),
}
CLASSES = ["BL", "CL", "DM", "JB", "LA", "PC", "RA", "SA", "SL", "SLA", "SRA"]


def get(d, path):
    for k in path:
        d = d[k]
    return d


def macro(name: str, value: str) -> str:
    return f"\\expandafter\\def\\csname {name}\\endcsname{{{value}}}\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--stats", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    runs = defaultdict(list)  # (variant, split) -> [json]
    for f in sorted(Path(args.results).glob("*_s*_*.json")):
        m = re.match(r"(.+)_s(\d+)_(val|test)\.json$", f.name)
        if m:
            runs[(m.group(1), m.group(3))].append(json.loads(f.read_text()))

    lines = ["% Auto-generated by experiments/make_tables.py -- do not edit by hand.\n"]
    vals = {}
    for (v, split), rs in sorted(runs.items()):
        lines.append(macro(f"res@{v}@{split}@nseeds", str(len(rs))))
        for name, (path, scale) in METRICS.items():
            x = np.array([get(r, path) for r in rs], float) * scale
            vals[(v, split, name)] = x.mean()
            lines.append(macro(f"res@{v}@{split}@{name}", f"{x.mean():.1f}"))
            lines.append(macro(f"resstd@{v}@{split}@{name}", f"{x.std(ddof=1) if len(x) > 1 else 0:.1f}"))
        for c in CLASSES:
            iou = np.array([r["IoU_per_class"][c] for r in rs], float) * 100
            lines.append(macro(f"res@{v}@{split}@iou{c}", f"{np.nanmean(iou):.1f}"))
            for key, nm in (("AP50_95", "ap"), ("AP50", "apfifty")):
                ap_ = np.array([r["mask_per_class"].get(c, {}).get(key, np.nan) for r in rs], float) * 100
                lines.append(macro(f"res@{v}@{split}@{nm}{c}", "--" if np.isnan(ap_).all() else f"{np.nanmean(ap_):.1f}"))
            b = np.array([r["BIoU_3px_per_class"][c] for r in rs], float) * 100
            lines.append(macro(f"res@{v}@{split}@biouthree{c}", f"{np.nanmean(b):.1f}"))
        lines.append(macro(f"res@{v}@{split}@params", f"{rs[0]['params_M']:.2f}"))
        sp = [r["speed"] for r in rs if r.get("speed", {}).get("fps")]
        if sp:
            lines.append(macro(f"res@{v}@{split}@fps", f"{sp[0]['fps']:.1f}"))
            lines.append(macro(f"res@{v}@{split}@gpu", sp[0]["device"]))
    for (v, split, name), x in vals.items():
        if ("baseline_p256", split, name) in vals:
            lines.append(macro(f"gain@{v}@{split}@{name}", f"{x - vals[('baseline_p256', split, name)]:+.1f}"))
        if ("baseline", split, name) in vals:
            lines.append(macro(f"gainstock@{v}@{split}@{name}", f"{x - vals[('baseline', split, name)]:+.1f}"))

    st = json.loads(Path(args.stats).read_text())
    for split in ("train", "val", "test"):
        for k in ("images", "scenes", "instances"):
            lines.append(macro(f"stat@{split}@{k}", f"{st[split][k]:,}"))
        for c in CLASSES:
            lines.append(macro(f"stat@{split}@{c}", str(st[split]["per_class"][c])))
    lines.append(macro("stat@all@dropped", str(st["train_images_dropped_scene_overlap_with_test"])))
    lines.append(macro("stat@all@valdev", f"{100 * st['max_class_fraction_deviation']:.1f}"))

    Path(args.out).write_text("".join(lines))
    print(f"Wrote {args.out} ({len(runs)} variant/split groups)")


if __name__ == "__main__":
    main()
